// bwBinary is the CLI this command drives. It is the standalone build, not the
// npm package, because the unit runs as a user with no node toolchain.
const bwBinary = "bw"

// generatedHeader tops the rendered file so nobody hand-edits it. The next pull
// overwrites the whole file, so an edit here is lost without warning.
const generatedHeader = "# Generated by `cairnos secrets pull`. Do not edit: the next pull replaces\n" +
	"# this file whole. Hand-written values belong in the env file beside it.\n"

// envFilePerm is the mode of the rendered file. It holds every credential the
// service starts with, so it matches the env file the service unit already reads.
const envFilePerm = 0o600

// cmdSecretsPull renders the configured vault fields into the service's second
// environment file. It runs at deployment rather than at run time because most
// of these values are read by bare os.Getenv, long before any runtime secret
// source exists to answer for them.
func (a *App) cmdSecretsPull(ctx context.Context, args []string) int {
	const label = "secrets pull"

	flags := flag.NewFlagSet(label, flag.ContinueOnError)
	flags.SetOutput(a.stderr)

	dirFlag := dirFlagOn(flags)
	dryRun := flags.Bool("dry-run", false, "resolve everything and report, without writing the file")
	system := flags.Bool("system", false,
		"write where a system-mode unit reads, under /etc/cairnos rather than the home")

	if code, proceed := parseFlags(flags, args); !proceed {
		return code
	}

	dir, err := resolveSecretsDir(*dirFlag, *system, a.envLookup())
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	configPath := filepath.Join(dir, configFileName)

	cfg, err := config.LoadWith(configPath, a.envLookup())
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	if cfg.Secrets.Bitwarden == nil {
		return a.reportNoVault(label, configPath)
	}

	opts := pullOptions{
		dir: dir, dirFlag: *dirFlag, cfg: &cfg, lookup: a.envLookup(), system: *system, dryRun: *dryRun,
	}

	return a.pullBitwarden(ctx, label, cfg.Secrets.Bitwarden, opts)
}

// resolveSecretsDir picks the home `secrets auth` and `secrets pull` read their
// config from.
// With --system and no --dir that is the system install's data directory, not
// the invoking user's: the documented `sudo cairnos secrets pull --system` would
// otherwise read /root/.cairnos/config.toml, find no block, and report success
// having written nothing.
func resolveSecretsDir(flagValue string, system bool, lookup environ.Lookup) (string, error) {
	if flagValue == "" && system {
		return service.SystemHome, nil
	}

	return resolveDir(flagValue, lookup)
}

// lookBitwardenBinary finds the bw the host itself provides, which the resolver
// prefers over the pinned copy whenever its version is not behind the pin. The
// search runs over the injected PATH rather than the process one.
func lookBitwardenBinary(lookup environ.Lookup) (string, error) {
	binary, err := environ.LookPath(lookup, bwBinary)
	if err != nil {
		return "", errNoBitwardenBinary
	}

	return binary, nil
}

// pullOptions carries where the pull writes and whether it writes at all, so
// the resolution rule lives in one place rather than in two signatures.
type pullOptions struct {
	// cfg is the loaded configuration, carried so the pull can warn about
	// credentials this host will want that the vault did not supply.
	cfg *config.Config

	// lookup is the injected environment, asked for the operator's home only
	// when a configured path starts with ~/.
	lookup environ.Lookup

	// dirFlag is the --dir the operator typed, empty when none, carried so a
	// command this one suggests reaches the same home.
	dirFlag string

	dir    string
	system bool
	dryRun bool
}

// commandFlags renders the --dir and --system this run was given, for a
// command it suggests next.
func (o pullOptions) commandFlags() string {
	var flags string

	if o.dirFlag != "" {
		flags += " --dir " + shellquote.Word(o.dirFlag)
	}

	if o.system {
		flags += " --system"
	}

	return flags
}

// pullBitwarden resolves the fields and renders the file, keeping cmdSecretsPull
// to flag handling and the no-config exit.
func (a *App) pullBitwarden(
	ctx context.Context, label string, block *config.Bitwarden, opts pullOptions,
) int {
	credsPath, err := opts.resolve(block.CredentialsFile, config.DefaultBitwardenCredentialsFile)
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	creds, err := bitwarden.LoadCredentials(credsPath, a.envLookup().Get)
	if err != nil {
		a.printErrf("%s: %v%s\n", label, err, authHint(err, credsPath, opts))

		return ExitFailure
	}

	itemName, err := resolveItem(block, creds)
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	item, err := a.readVaultItem(ctx, opts.dir, creds, itemName)
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	values, err := planValues(opts.cfg, item, block.Fields)
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	a.warnMissingImplied(label, opts.cfg, values)

	target, err := opts.resolve(block.EnvFile, config.DefaultBitwardenEnvFile)
	if err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	return a.renderEnvFile(label, target, values, opts.dryRun)
}

// authHint names the command that creates the credentials file when the pull
// found none, with this run's --dir and --system so it sets up the same file.
// An existing file gets no hint, since auth checks it rather than rewriting it
// and would repeat this error. Nor does an absent chezmoi config, which auth
// refuses to create.
func authHint(err error, credsPath string, opts pullOptions) string {
	if !errors.Is(err, bitwarden.ErrMissingCredentials) || bitwarden.IsChezmoiConfig(credsPath) {
		return ""
	}

	if _, statErr := os.Lstat(credsPath); !errors.Is(statErr, fs.ErrNotExist) {
		return ""
	}

	return "; run cairnos secrets auth" + opts.commandFlags() + " to set them up"
}

// warnMissingImplied reports credentials this configuration will want that the
// vault did not supply. It never fails the pull: a host may hold one of these in
// its hand-written env file, and refusing to deploy over that would be wrong
// more often than right.
func (a *App) warnMissingImplied(label string, cfg *config.Config, values map[string]string) {
	missing := missingImplied(cfg, values)
	if len(missing) == 0 {
		return
	}

	a.printErrf("%s: warning: this config expects %s, which the item does not carry\n",
		label, joinNames(missing))

	if mattermostOverrideApplies(cfg, values) {
		a.printErrf("%s: an identity can take its token from "+
			"CAIRNOS_BRIDGE_MATTERMOST_<ID>_TOKEN instead, or from the name its "+
			"token_env sets\n", label)
	}
}

// resolve decides where one of the two files lives. A configured value goes
// through resolveHomePath. A default goes through the service package, which is
// what decides where the unit reads from: a system unit loads /etc/cairnos,
// never the home.
func (o pullOptions) resolve(configured, fallback string) (string, error) {
	if configured != fallback {
		return resolveHomePath(o.dir, configured, o.lookup)
	}

	if fallback == config.DefaultBitwardenEnvFile {
		return service.SecretsEnvFile(o.dir, o.system), nil
	}

	return filepath.Join(service.EnvDir(o.dir, o.system), fallback), nil
}

// renderEnvFile writes the file and reports what went into it. Only variable
// names and the path are printed: this runs in a deploy log that is not treated
// as secret.
func (a *App) renderEnvFile(label, path string, values map[string]string, dryRun bool) int {
	names := sortedKeys(values)

	if err := checkRenderable(names, values); err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	rendered := renderEnv(names, values)

	if dryRun {
		a.printOutf("%s: would write %s (%d variables): %s\n",
			label, path, len(names), strings.Join(names, " "))

		return ExitOK
	}

	if err := a.writeFileAtomic(path, rendered, envFilePerm); err != nil {
		a.printErrf("%s: %v\n", label, err)

		return ExitFailure
	}

	a.printOutf("%s: wrote %s (%d variables): %s\n",
		label, path, len(names), strings.Join(names, " "))

	return ExitOK
}

// renderEnv sorts so an unchanged vault produces identical bytes. Every value is
// single-quoted because systemd's EnvironmentFile and the POSIX shell that
// sources this on macOS both split an unquoted one into words, so a value with a
// space would set half a variable and run the rest as a command.
func renderEnv(names []string, values map[string]string) []byte {
	var out strings.Builder

	out.WriteString(generatedHeader)

	for _, name := range names {
		fmt.Fprintf(&out, "%s=%s\n", name, shellquote.Word(values[name]))
	}

	return []byte(out.String())
}

// checkRenderable refuses a value neither reader can carry. Both parse line by
// line, so an embedded newline would end the assignment early and leave the
// remainder to be read as a second one. Naming every offender at once keeps this
// consistent with how a missing field is reported.
func checkRenderable(names []string, values map[string]string) error {
	var offenders []string

	for _, name := range names {
		if hasLineBreak(values[name]) {
			offenders = append(offenders, name)
		}
	}

	if len(offenders) == 0 {
		return nil
	}

	return fmt.Errorf("%w: %s", errValueHasNewline, strings.Join(offenders, ", "))
}

// hasLineBreak reports a value a line-based file cannot carry: the reader would
// end the assignment at the break and read the rest as a line of its own.
func hasLineBreak(value string) bool {
	return strings.ContainsAny(value, "\n\r")
}

// sortedKeys lists the mapping's variable names in order.
func sortedKeys(fields map[string]string) []string {
	names := make([]string, 0, len(fields))
	for name := range fields {
		names = append(names, name)
	}

	sort.Strings(names)

	return names
}

// resolveHomePath keeps an absolute path, expands a leading ~/ against the
// operator's home, and resolves anything else against the CairnOS home as the
// sqlite dsn does. TOML never shell-expands a string, so without the ~/ case a
// chezmoi pointer would land under the CairnOS home, read as absent, and leave
// the pull on the environment without a word.
func resolveHomePath(dir, path string, lookup environ.Lookup) (string, error) {
	if filepath.IsAbs(path) {
		return path, nil
	}

	underHome, isTilde := strings.CutPrefix(path, "~/")
	if !isTilde {
		return filepath.Join(dir, path), nil
	}

	home, err := homeDir(lookup)
	if err != nil {
		return "", fmt.Errorf("expand %s: %w", path, err)
	}

	return filepath.Join(home, underHome), nil
}

// writeFileAtomic writes through a temp file in the same directory and renames,
// so a failure part way leaves the previous file intact rather than a truncated
// one the service would start against. The replaced file keeps its owner, as an
// in-place write would. The temp file is removed on every failure path, so a
// failed pull leaves nothing behind.
func (a *App) writeFileAtomic(path string, content []byte, perm os.FileMode) error {
	uid, gid, chown, err := ownerToKeep(path)
	if err != nil {
		return err
	}

	dir := filepath.Dir(path)

	tempPath, err := stageTemp(dir, filepath.Base(path), content, perm)
	if err != nil {
		return err
	}

	if chown {
		if err := os.Chown(tempPath, uid, gid); err != nil {
			return errors.Join(fmt.Errorf("keep the owner of %s: %w", path, err), removeLeftover(tempPath))
		}
	}

	if err := os.Rename(tempPath, path); err != nil {
		return errors.Join(fmt.Errorf("replace %s: %w", path, err), removeLeftover(tempPath))
	}

	if err := syncDir(dir); err != nil {
		a.logger.Warn("the rename landed but the directory was not flushed",
			"dir", dir, "error", err)
	}

	return nil
}

// createFileAtomic publishes content at path only when nothing is there yet.
// The hard link fails on an existing name, so a file that appeared since the
// caller looked is kept rather than replaced, and the content is whole before
// the name exists.
func (a *App) createFileAtomic(path string, content []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)

	tempPath, err := stageTemp(dir, filepath.Base(path), content, perm)
	if err != nil {
		return err
	}

	var linkErr error

	if err := os.Link(tempPath, path); err != nil {
		linkErr = fmt.Errorf("create %s: %w", path, err)
	}

	if err := errors.Join(linkErr, removeLeftover(tempPath)); err != nil {
		return err
	}

	if err := syncDir(dir); err != nil {
		a.logger.Warn("the file landed but the directory was not flushed", "dir", dir, "error", err)
	}

	return nil
}

// stageTemp writes content to a fresh temp file in dir at perm and returns its
// path, removing it again when the write fails.
func stageTemp(dir, base string, content []byte, perm os.FileMode) (string, error) {
	temp, err := os.CreateTemp(dir, base+".*")
	if err != nil {
		return "", fmt.Errorf("create a temp file in %s: %w", dir, err)
	}

	if err := finishTempFile(temp, content, perm); err != nil {
		return "", errors.Join(err, removeLeftover(temp.Name()))
	}

	return temp.Name(), nil
}

// ownerToKeep returns the owner a replace of path must restore, and whether a
// chown is needed for it, refusing a caller that could not restore it.
func ownerToKeep(path string) (int, int, bool, error) {
	uid, gid, present, err := fileOwner(path)
	if err != nil || !present {
		return 0, 0, false, err
	}

	chown, err := KeepOwnerPlan(path, uid, os.Geteuid())

	return uid, gid, chown, err
}

// reportNoVault prints the no-op line and exits clean. A host with no
// [secrets.bitwarden] block is the ordinary case, since deploy runs this
// unconditionally and a non-zero exit would stop every such host. The path is
// named because the other way here is a command that read the wrong config.
func (a *App) reportNoVault(label, configPath string) int {
	a.printOutf("%s: no [secrets.bitwarden] block in %s, nothing to do\n", label, configPath)

	return ExitOK
}

// syncDir flushes the directory entry the rename created, which is what makes
// the rename survive a crash now that the contents are already synced. A
// filesystem that refuses the call still has the file in place, so the caller
// warns rather than failing a deploy that worked.
func syncDir(dir string) error {
	handle, err := os.Open(dir) // #nosec G304 -- the directory holds the target file
	if err != nil {
		return fmt.Errorf("open %s to flush the rename: %w", dir, err)
	}

	defer func() { _ = handle.Close() }()

	if err := handle.Sync(); err != nil {
		return fmt.Errorf("flush %s: %w", dir, err)
	}

	return nil
}

// finishTempFile writes the body, sets the mode, and closes, so writeFileAtomic
// has one error path to clean up after. The close error is returned rather than
// discarded: this is a file the function wrote through, so a close can still
// report a failed flush. The chmod states the mode the unit depends on rather
// than inheriting os.CreateTemp's.
func finishTempFile(temp *os.File, content []byte, perm os.FileMode) (err error) {
	defer func() {
		if closeErr := temp.Close(); closeErr != nil && err == nil {
			err = fmt.Errorf("close %s: %w", temp.Name(), closeErr)
		}
	}()

	if _, err := temp.Write(content); err != nil {
		return fmt.Errorf("write %s: %w", temp.Name(), err)
	}

	if err := temp.Chmod(perm); err != nil {
		return fmt.Errorf("set the mode of %s: %w", temp.Name(), err)
	}

	if err := temp.Sync(); err != nil {
		return fmt.Errorf("flush %s: %w", temp.Name(), err)
	}

	return nil
}
