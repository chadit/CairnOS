// Package bwpin refreshes the pinned Bitwarden CLI release recorded in
// internal/cli/bwpin_gen.go. The command that drives it is tools/bwpin; the
// work lives here so it can be tested from outside.
//
// Bitwarden publishes no checksum file for the CLI assets, so the only way to
// learn a release's digests is to download both platform archives and hash
// them, along with the single binary each one holds. That is around 90 MB of
// traffic per bump, which is why this is a command an operator runs rather than
// something a build does.
package bwpin

import (
	"archive/zip"
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io"
	"io/fs"
	"log/slog"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"text/template"
	"time"

	"github.com/chadit/CairnOS/internal/bwinstall"
)

// Where the tool reads and writes by default. Both URL bases are flags, which
// is what lets the suite point them at a local server instead of GitHub.
const (
	DefaultOut      = "internal/cli/bwpin_gen.go"
	DefaultAPI      = "https://api.github.com"
	DefaultDownload = "https://github.com/bitwarden/clients/releases/download"
)

// clientsRepo is the repository every Bitwarden client is released from, and
// tagPrefix what separates a CLI release from a web vault or desktop one. The
// repository's `latest` release is usually not a CLI release, so the list has
// to be walked and filtered rather than polled at one endpoint.
const (
	clientsRepo = "bitwarden/clients"
	tagPrefix   = "cli-v"
)

// entryName is the one file each platform archive holds, and the file the
// installer takes out of it.
const entryName = "bw"

// releasesPerPage is the API's maximum, and maxReleasePages bounds the walk
// back through the feed. Every client releases from one repository, so CLI
// releases are a fraction of it; five full pages is roughly a year, and a gap
// wider than that means the tag pattern moved rather than that paging should
// continue.
const (
	releasesPerPage = 100
	maxReleasePages = 5
)

// Size caps. An asset is around 45 MB today and a release listing a few hundred
// kilobytes, so these leave room to grow without letting a redirected or
// hostile response write until the disk fills.
const (
	maxAssetBytes = 256 << 20
	maxListBytes  = 8 << 20
)

// downloadTimeout bounds one asset fetch on a home connection, and
// generatedPerm is the mode of the file this tool writes: a source file, read
// like the rest of the tree.
const (
	downloadTimeout = 10 * time.Minute
	generatedPerm   = 0o644
)

// versionFields is how many dot-separated numbers a CLI version carries, and
// maxRedirects the hop limit the standard library applies until a custom
// CheckRedirect replaces it.
const (
	versionFields = 3
	maxRedirects  = 10
)

// httpsScheme is the only URL scheme a fetch or a redirect hop may use.
const httpsScheme = "https"

// fileTemplate is the whole generated file. The header is the marker linters
// and reviewers both read, so it stays on the first line.
const fileTemplate = `// Code generated by tools/bwpin. DO NOT EDIT.

package cli

// The pinned Bitwarden CLI release and the four digests an install checks it
// against: each platform's archive as published, and the single bw binary
// inside that archive. Upstream publishes no checksum file for these assets, so
// tools/bwpin downloads both archives and hashes them.
const (
	bwVersion = "{{ .Version }}"

	bwLinuxArchiveSHA256 = "{{ .Linux.Archive }}"
	bwLinuxBinarySHA256 = "{{ .Linux.Binary }}"

	bwMacOSArchiveSHA256 = "{{ .MacOS.Archive }}"
	bwMacOSBinarySHA256 = "{{ .MacOS.Binary }}"
)
`

// Config is one Run: where releases and assets are read from, and the file to
// rewrite. client is nil outside tests, which is what selects the default.
type Config struct {
	// Client is the HTTP client the fetches use, and Logger where progress
	// goes. Both may be nil, which takes the package defaults.
	Client *http.Client
	Logger *slog.Logger

	// API is the base of the GitHub API, Download the base of the release
	// assets, and Out the generated file to rewrite.
	API      string
	Download string
	Out      string
}

// assetDigests is one platform's pair: the archive as published, and the binary
// inside it. Fields are exported because the template reads them.
type assetDigests struct {
	Archive string
	Binary  string
}

// pinFile is what the template renders.
type pinFile struct {
	Version string
	Linux   assetDigests
	MacOS   assetDigests
}

// release is the part of a GitHub release this tool reads.
type release struct {
	TagName    string `json:"tag_name"`
	Draft      bool   `json:"draft"`
	Prerelease bool   `json:"prerelease"`
}

// Run compares the newest CLI release to the pin on disk and rewrites the file
// when they differ. An unchanged pin downloads nothing: the two archives are
// most of a minute even on a fast link.
func Run(ctx context.Context, cfg Config) error {
	logger := cfg.log()

	current, err := CurrentVersion(cfg.Out)
	if err != nil {
		return err
	}

	latest, err := latestRelease(ctx, cfg)
	if err != nil {
		return err
	}

	if latest == current {
		logger.Info("the pinned Bitwarden CLI is the newest release", "version", current, "file", cfg.Out)

		return nil
	}

	logger.Info("a newer Bitwarden CLI release is out", "pinned", current, "latest", latest)

	pins, err := digests(ctx, cfg, latest, logger)
	if err != nil {
		return err
	}

	if err := render(cfg.Out, &pins); err != nil {
		return err
	}

	logger.Info("rewrote the pin", "file", cfg.Out, "version", latest)

	return nil
}

// CurrentVersion reads the pin the generated file carries today. A file that is
// not there yet is not a failure: the Run that follows writes it.
func CurrentVersion(path string) (string, error) {
	body, err := os.ReadFile(path) // #nosec G304 -- the operator names the file to rewrite
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}

	if err != nil {
		return "", fmt.Errorf("read %s: %w", path, err)
	}

	match := regexp.MustCompile(`bwVersion\s*=\s*"([^"]+)"`).FindSubmatch(body)
	if match == nil {
		return "", fmt.Errorf("%w: %s", ErrNoVersionLine, path)
	}

	return string(match[1]), nil
}

// latestRelease walks the release feed and returns the highest CLI version it
// finds. The repository's own `latest` endpoint answers with whichever client
// shipped most recently, which is usually not this one.
func latestRelease(ctx context.Context, cfg Config) (string, error) {
	pattern := regexp.MustCompile(`^` + tagPrefix + `(\d+)\.(\d+)\.(\d+)$`)

	var best string

	for page := 1; page <= maxReleasePages; page++ {
		releases, err := releasePage(ctx, cfg, page)
		if err != nil {
			return "", err
		}

		if len(releases) == 0 {
			break
		}

		best = highest(best, releases, pattern)

		if atFeedEnd(releases) {
			break
		}
	}

	if best == "" {
		return "", fmt.Errorf("%w: %s", ErrNoCLIRelease, cfg.API)
	}

	return best, nil
}

// atFeedEnd reports whether a short page has ended the release feed. Walking on
// past one spends calls against an hourly budget update-deps.sh shares.
func atFeedEnd(releases []release) bool {
	return len(releases) < releasesPerPage
}

// highest returns the greater of the version already found and the CLI versions
// on this page. A draft or a prerelease is skipped: hosts follow this pin
// without being asked, so a release upstream has not finished is not one to
// hand them.
func highest(best string, releases []release, pattern *regexp.Regexp) string {
	for _, entry := range releases {
		if entry.Draft || entry.Prerelease || !pattern.MatchString(entry.TagName) {
			continue
		}

		if version := strings.TrimPrefix(entry.TagName, tagPrefix); newer(version, best) {
			best = version
		}
	}

	return best
}

// newer reports whether left sorts above right. CLI versions are calendar
// shaped, so a string compare puts 2026.10.0 below 2026.9.0; the fields are
// compared as numbers instead.
func newer(left, right string) bool {
	if right == "" {
		return true
	}

	leftFields, rightFields := versionFieldsOf(left), versionFieldsOf(right)
	for index := range leftFields {
		if leftFields[index] != rightFields[index] {
			return leftFields[index] > rightFields[index]
		}
	}

	return false
}

// versionFieldsOf splits a version into its three numbers. Every caller passes
// a string the tag pattern already matched, so a field that will not parse
// means the pattern and this function disagree, and the zero sorts it last.
func versionFieldsOf(version string) [versionFields]int {
	var fields [versionFields]int

	for index, field := range strings.SplitN(version, ".", versionFields) {
		value, err := strconv.Atoi(field)
		if err != nil {
			return fields
		}

		fields[index] = value
	}

	return fields
}

// releasePage reads one page of the release feed.
func releasePage(ctx context.Context, cfg Config, page int) ([]release, error) {
	target := fmt.Sprintf("%s/repos/%s/releases?per_page=%d&page=%d",
		cfg.API, clientsRepo, releasesPerPage, page)

	body, err := get(ctx, cfg, target)
	if err != nil {
		return nil, err
	}

	defer func() { _ = body.Close() }()

	var releases []release
	if err := json.NewDecoder(io.LimitReader(body, maxListBytes)).Decode(&releases); err != nil {
		return nil, fmt.Errorf("parse the release list from %s: %w", target, err)
	}

	return releases, nil
}

// digests downloads both platform archives and hashes each one and the binary
// inside it. Four digests, two downloads, and no way around either: upstream
// publishes nothing to read them from.
func digests(
	ctx context.Context, cfg Config, version string, logger *slog.Logger,
) (pinFile, error) {
	pins := pinFile{Version: version}

	for _, platform := range []struct {
		into *assetDigests
		name string
	}{
		{name: "linux", into: &pins.Linux},
		{name: "macos", into: &pins.MacOS},
	} {
		target := fmt.Sprintf("%s/%s%s/bw-%s-%s.zip",
			cfg.Download, tagPrefix, version, platform.name, version)

		logger.Info("downloading a release asset", "url", target)

		pin, err := assetPin(ctx, cfg, target)
		if err != nil {
			return pinFile{}, err
		}

		*platform.into = pin
	}

	return pins, nil
}

// assetPin fetches one archive and returns both of its digests. The body goes
// to a temp file rather than memory because the archive reader needs to seek.
func assetPin(ctx context.Context, cfg Config, target string) (assetDigests, error) {
	body, err := get(ctx, cfg, target)
	if err != nil {
		return assetDigests{}, err
	}

	defer func() { _ = body.Close() }()

	temp, err := os.CreateTemp("", "bwpin-*.zip")
	if err != nil {
		return assetDigests{}, fmt.Errorf("create a temp file for %s: %w", target, err)
	}

	defer func() {
		if removeErr := os.Remove(temp.Name()); removeErr != nil {
			cfg.log().Warn("remove the downloaded archive", "path", temp.Name(), "error", removeErr)
		}
	}()

	archive, err := drain(temp, body)
	if err != nil {
		return assetDigests{}, err
	}

	binary, err := binaryDigest(temp.Name())
	if err != nil {
		return assetDigests{}, err
	}

	return assetDigests{Archive: archive, Binary: binary}, nil
}

// drain copies the response into the temp file under the size cap and returns
// the digest of what it wrote. The file is closed here so the archive reader
// can open it, and so a write failure is reported rather than discarded.
func drain(temp *os.File, source io.Reader) (string, error) {
	digest := sha256.New()

	written, err := io.Copy(io.MultiWriter(temp, digest), io.LimitReader(source, maxAssetBytes+1))

	if closeErr := temp.Close(); closeErr != nil && err == nil {
		err = closeErr
	}

	if err != nil {
		return "", fmt.Errorf("write %s: %w", temp.Name(), err)
	}

	if written > maxAssetBytes {
		return "", fmt.Errorf("%w: %s took more than %d bytes", ErrTooLarge, temp.Name(), maxAssetBytes)
	}

	return hex.EncodeToString(digest.Sum(nil)), nil
}

// binaryDigest hashes the bw entry through the same reader the installer uses,
// because the digest this writes is the one that install compares against.
func binaryDigest(path string) (string, error) {
	reader, err := zip.OpenReader(path)
	if err != nil {
		return "", fmt.Errorf("read %s as a zip: %w", path, err)
	}

	defer func() { _ = reader.Close() }()

	entry, err := soleEntry(reader)
	if err != nil {
		return "", err
	}

	source, err := entry.Open()
	if err != nil {
		return "", fmt.Errorf("open %s inside %s: %w", entry.Name, path, err)
	}

	defer func() { _ = source.Close() }()

	sum, err := bwinstall.EntryDigest(source)
	if err != nil {
		return "", fmt.Errorf("hash %s inside %s: %w", entry.Name, path, err)
	}

	return sum, nil
}

// soleEntry returns the archive's single bw entry. A second entry, another
// name, or anything but a regular file means the release layout moved, and a
// digest taken from the wrong entry would fail every install that trusted it.
func soleEntry(reader *zip.ReadCloser) (*zip.File, error) {
	if len(reader.File) != 1 {
		return nil, fmt.Errorf("%w: it holds %d entries", ErrArchiveLayout, len(reader.File))
	}

	entry := reader.File[0]
	if entry.Name != entryName || !entry.Mode().IsRegular() {
		return nil, fmt.Errorf("%w: it holds %q at mode %s", ErrArchiveLayout, entry.Name, entry.Mode())
	}

	return entry, nil
}

// get opens one request, refusing anything but https for the reason bwinstall
// does: nothing authenticates where bytes from a plain http URL came from, and
// these bytes become a compiled-in digest.
func get(ctx context.Context, cfg Config, target string) (io.ReadCloser, error) {
	parsed, err := url.Parse(target)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", target, err)
	}

	if parsed.Scheme != httpsScheme {
		return nil, fmt.Errorf("%w: %s", ErrNotHTTPS, target)
	}

	request, err := http.NewRequestWithContext(ctx, http.MethodGet, target, http.NoBody)
	if err != nil {
		return nil, fmt.Errorf("build a request for %s: %w", target, err)
	}

	request.Header.Set("Accept", "application/vnd.github+json")

	response, err := cfg.httpClient().Do(request)
	if err != nil {
		return nil, fmt.Errorf("fetch %s: %w", target, err)
	}

	if response.StatusCode != http.StatusOK {
		_ = response.Body.Close()

		return nil, fmt.Errorf("%w: %s answered HTTP %d", ErrBadStatus, target, response.StatusCode)
	}

	return response.Body, nil
}

// log resolves where progress lines go, so Run can write one without a nil
// check of its own.
func (c Config) log() *slog.Logger {
	if c.Logger != nil {
		return c.Logger
	}

	return slog.Default()
}

// httpClient resolves the client and installs the redirect guard on whichever
// one it hands back, so a caller supplying its own cannot end up without the
// guard. The default carries a timeout because each asset is tens of megabytes
// and a stalled body would otherwise hold the bump open with nothing on screen.
func (c Config) httpClient() *http.Client {
	client := http.Client{Timeout: downloadTimeout}
	if c.Client != nil {
		client = *c.Client
	}

	client.CheckRedirect = refuseDowngrade

	return &client
}

// refuseDowngrade stops a redirect chain that leaves https, and keeps the hop
// limit that setting CheckRedirect otherwise replaces with no limit at all.
// Checking the URL this tool built says nothing about where a redirect lands,
// and the bytes at the end of the chain become the digests the whole fleet
// installs without asking.
func refuseDowngrade(request *http.Request, via []*http.Request) error {
	if request.URL.Scheme != httpsScheme {
		return fmt.Errorf("%w: the download was redirected to %s", ErrNotHTTPS, request.URL)
	}

	if len(via) >= maxRedirects {
		return fmt.Errorf("%w: the download was redirected %d times", ErrBadStatus, len(via))
	}

	return nil
}

// render writes the generated file through go/format, so the result is the
// bytes the formatter would produce and a bump shows only the lines that moved.
func render(path string, pins *pinFile) error {
	var body bytes.Buffer

	if err := template.Must(template.New("pin").Parse(fileTemplate)).Execute(&body, pins); err != nil {
		return fmt.Errorf("render %s: %w", path, err)
	}

	formatted, err := format.Source(body.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}

	return writeAtomic(path, formatted)
}

// writeAtomic replaces the file through a temp file in the same directory, so a
// failure part way leaves the previous pin intact rather than a half-written
// file that will not compile.
func writeAtomic(path string, body []byte) error {
	dir := filepath.Dir(path)

	temp, err := os.CreateTemp(dir, filepath.Base(path)+".*")
	if err != nil {
		return fmt.Errorf("create a temp file in %s: %w", dir, err)
	}

	if err := finish(temp, body); err != nil {
		return discardTemp(temp.Name(), err)
	}

	if err := os.Rename(temp.Name(), path); err != nil {
		return discardTemp(temp.Name(), fmt.Errorf("replace %s: %w", path, err))
	}

	return nil
}

// discardTemp removes the temp file a failed write left and returns cause. A
// temp file that will not go away is joined onto cause, since it sits beside
// checked-in source and the person running the tool has to delete it.
func discardTemp(name string, cause error) error {
	if err := os.Remove(name); err != nil {
		return errors.Join(cause, fmt.Errorf("remove the temp file %s: %w", name, err))
	}

	return cause
}

// finish writes the body, resets the 0600 mode os.CreateTemp left behind to the
// one checked-in source carries, and closes, so writeAtomic has one failure path
// to clean up after.
func finish(temp *os.File, body []byte) (err error) {
	defer func() {
		if closeErr := temp.Close(); closeErr != nil && err == nil {
			err = fmt.Errorf("close %s: %w", temp.Name(), closeErr)
		}
	}()

	if _, err := temp.Write(body); err != nil {
		return fmt.Errorf("write %s: %w", temp.Name(), err)
	}

	if err := temp.Chmod(generatedPerm); err != nil {
		return fmt.Errorf("set the mode of %s: %w", temp.Name(), err)
	}

	return nil
}
